"""Per-product git repositories and worker worktrees.

Each product owns an independent git repository under data/products/<product>.
Parallel workers get their own worktree on a dedicated branch, commit there,
and finished branches are merged back into the target branch.
"""
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

# Identity is fixed so generated commits are attributable.
GIT_IDENTITY = {
    "GIT_AUTHOR_NAME": "ACP Software Factory",
    "GIT_AUTHOR_EMAIL": "factory@localhost",
    "GIT_COMMITTER_NAME": "ACP Software Factory",
    "GIT_COMMITTER_EMAIL": "factory@localhost",
}

# Never let a product repository inherit unsafe global git behavior.
GIT_CONFIG = (
    "-c", "commit.gpgsign=false",
    "-c", "core.hooksPath=/dev/null",
    "-c", "advice.detachedHead=false",
)


class GitError(RuntimeError):
    """A git command failed."""


def _clean_env() -> dict[str, str]:
    env = {key: os.environ[key] for key in ("PATH", "HOME", "LANG") if key in os.environ}
    env.update(GIT_IDENTITY)
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    env["GIT_TERMINAL_PROMPT"] = "0"
    return env


def _run(argv: list[str], cwd: Path | str, timeout: int = 120, env: dict[str, str] | None = None) -> str:
    try:
        result = subprocess.run(
            ["git", *GIT_CONFIG, *argv],
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=timeout,
            env=env if env is not None else _clean_env(),
        )
    except subprocess.TimeoutExpired as exc:
        raise GitError(f"git {argv[0]} timed out after {timeout}s") from exc
    except OSError as exc:
        raise GitError(f"git {argv[0]} could not start: {exc.__class__.__name__}") from exc

    if result.returncode != 0:
        err = (result.stderr or result.stdout)[-2000:]
        raise GitError(f"git {argv[0]} failed ({result.returncode}): {err}")
    return result.stdout.strip()


def product_root(data_dir: Path | str, product_id: str) -> Path:
    p = Path(data_dir)
    if p.name == "products":
        return p / product_id
    return p / "products" / product_id


PRODUCT_GITIGNORE = """\
# Generated by ACP Factory. Build and runtime artifacts ignored.
node_modules/
dist/
build/
release/
.next/
.nuxt/
.output/
target/
zig-out/
.zig-cache/
__pycache__/
*.pyc
.venv/

# Local runtime state.
*.sqlite
*.sqlite3
*.db
.env
.env.*
"""


def _write(root: Path, files: dict[str, str | bytes]) -> None:
    for name, content in files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            target.write_bytes(content)
        else:
            target.write_text(content, encoding="utf-8")


def ensure_repo(data_dir: Path, product_id: str, seed_files: dict[str, str | bytes] | None = None) -> Path:
    """Create the product repository on first use and return its path."""
    root = product_root(data_dir, product_id)
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    if not (root / ".git").exists():
        _run(["init", "-q", "-b", "main"], cwd=root)
        _run(["commit", "-q", "--allow-empty", "-m", "Initialize product repository"], cwd=root)
        _write(root, {".gitignore": PRODUCT_GITIGNORE})
        _run(["add", "-A"], cwd=root)
        _run(["commit", "-q", "-m", "Ignore build output"], cwd=root)
        if seed_files:
            _write(root, seed_files)
            _run(["add", "-A"], cwd=root)
            _run(["commit", "-q", "-m", "Add initial project files"], cwd=root)
    elif not (root / ".gitignore").is_file():
        _write(root, {".gitignore": PRODUCT_GITIGNORE})
        _run(["add", "-A"], cwd=root)
        _run(["commit", "-q", "-m", "Ignore build output"], cwd=root)
    return root


def target_branch(root: Path) -> str:
    return _run(["rev-parse", "--abbrev-ref", "HEAD"], cwd=root)


def head_commit(root: Path) -> str:
    return _run(["rev-parse", "HEAD"], cwd=root)


def worktree_add(root: Path, destination: Path, branch: str) -> Path:
    """Create an isolated worktree on a new branch based on current HEAD."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    _run(["worktree", "add", "-q", "-b", branch, str(destination)], cwd=root)
    return destination


def worktree_remove(root: Path, destination: Path) -> None:
    """Safely remove a worktree and prune."""
    try:
        _run(["worktree", "remove", "--force", str(destination)], cwd=root)
    except GitError:
        pass
    try:
        _run(["worktree", "prune"], cwd=root)
    except GitError:
        pass


def branch_delete(root: Path, branch: str) -> None:
    """Delete a branch."""
    try:
        _run(["branch", "-D", branch], cwd=root)
    except GitError:
        pass


def branch_exists(root: Path, branch: str) -> bool:
    """True if branch exists in the repository."""
    try:
        _run(["rev-parse", "--verify", f"refs/heads/{branch}"], cwd=root)
        return True
    except GitError:
        return False


def is_ancestor(root: Path, ancestor: str, descendant: str) -> bool:
    """True if ancestor commit is reachable from descendant."""
    try:
        _run(["merge-base", "--is-ancestor", ancestor, descendant], cwd=root)
        return True
    except GitError:
        return False


def is_worktree_valid(root: Path, worktree: Path, branch: str, expected_base: str) -> bool:
    """True if worktree is healthy, on branch, and branched from expected_base."""
    if not (worktree.is_dir() and (worktree / ".git").is_file()):
        return False
    if not branch_exists(root, branch):
        return False
    try:
        cur = _run(["rev-parse", "--abbrev-ref", "HEAD"], cwd=worktree)
        if cur != branch:
            return False
        merge_base = _run(["merge-base", expected_base, "HEAD"], cwd=worktree)
        if merge_base == expected_base:
            return True
        if is_ancestor(root, merge_base, expected_base):
            try:
                _run(["merge", "--no-edit", expected_base], cwd=worktree)
                return True
            except GitError:
                try:
                    _run(["merge", "--abort"], cwd=worktree)
                except GitError:
                    pass
                return False
        return False
    except GitError:
        return False


def clean_worktree(worktree: Path) -> None:
    """Reset any uncommitted or untracked changes in the worktree."""
    try:
        _run(["reset", "--hard", "HEAD"], cwd=worktree)
        _run(["clean", "-fd"], cwd=worktree)
    except GitError:
        pass


def commit_all(worktree: Path, message: str) -> str:
    """Stage everything and commit. Returns new commit hash."""
    _run(["add", "-A"], cwd=worktree)
    status = _run(["status", "--porcelain"], cwd=worktree)
    if not status:
        return head_commit(worktree)
    _run(["commit", "-q", "-m", message], cwd=worktree)
    return head_commit(worktree)


LOCKFILE_NAMES = ("package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb")
LOCKFILE_PATHSPECS = [f":(exclude,glob)**/{name}" for name in LOCKFILE_NAMES]


def diff_against_base(worktree: Path, base_commit: str, max_bytes: int = 200_000) -> str:
    """Unified diff of the worktree against base_commit, truncated if oversize."""
    text = _run(
        ["diff", "--no-color", "--no-ext-diff", base_commit, "--", ".", *LOCKFILE_PATHSPECS],
        cwd=worktree,
        timeout=60,
    )
    if len(text) <= max_bytes:
        return text
    note = (
        f"\n\n[DIFF TRUNCATED: showing the first {max_bytes} of {len(text)} characters. "
        "Files listed as changed but not shown here were cut by this limit, not omitted by the worker. "
        "Do not report a file as missing on the strength of this truncation.]\n"
    )
    return text[:max_bytes] + note


def diff_against(worktree: Path, base: str, limit: int = 200_000) -> str:
    """Alias for diff_against_base."""
    return diff_against_base(worktree, base, max_bytes=limit)


def changed_files(worktree: Path, base: str) -> list[str]:
    """Files that differ from base, including untracked ones."""
    tracked = _run(["diff", "--name-only", base, "--"], cwd=worktree, timeout=60)
    untracked = _run(["ls-files", "--others", "--exclude-standard"], cwd=worktree, timeout=60)
    names = [line for line in tracked.splitlines() if line.strip()]
    names += [line for line in untracked.splitlines() if line.strip()]
    return list(dict.fromkeys(names))


def merge_branch(root: Path, branch: str, message: str | None = None) -> tuple[bool, str]:
    """Merge branch into target HEAD. If conflict, abort merge and return (False, "Merge conflict")."""
    msg = message or f"Merge branch {branch}"
    try:
        _run(["merge", "--no-ff", "--no-edit", "-m", msg, branch], cwd=root, timeout=120)
        return True, head_commit(root)
    except GitError:
        try:
            _run(["merge", "--abort"], cwd=root)
        except GitError:
            pass
        return False, "Merge conflict"


def checkout_target(root: Path) -> None:
    branch = target_branch(root)
    if branch != "main":
        _run(["checkout", "-q", "main"], cwd=root)


def list_worktrees(root: Path) -> list[dict[str, Any]]:
    out = _run(["worktree", "list", "--porcelain"], cwd=root)
    entries: list[dict[str, Any]] = []
    current: dict[str, Any] = {}
    for line in out.splitlines():
        if not line.strip():
            if current:
                entries.append(current)
            current = {}
        elif line.startswith("worktree "):
            current["path"] = line[len("worktree "):]
        elif line.startswith("branch "):
            current["branch"] = line[len("branch "):].removeprefix("refs/heads/")
        elif line.startswith("HEAD "):
            current["head"] = line[len("HEAD "):]
    if current:
        entries.append(current)
    return entries


def export_tree(root: Path, destination: Path) -> Path:
    """Copy the tracked files of target branch into destination."""
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    listing = _run(["ls-tree", "-r", "--name-only", "HEAD"], cwd=root, timeout=60)
    for name in [line for line in listing.splitlines() if line.strip()]:
        source = root / name
        if not source.is_file() or source.is_symlink():
            continue
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    return destination


def export_tree_worktree(worktree: Path, destination: Path) -> Path:
    """Copy worktree files without git metadata."""
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    for path in sorted(worktree.rglob("*")):
        if ".git" in path.relative_to(worktree).parts:
            continue
        relative = path.relative_to(worktree)
        if path.is_symlink() or not path.is_file():
            continue
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    return destination


def ancestors(root: Path, limit: int = 500) -> set[str]:
    """Commits reachable from target branch."""
    out = _run(["rev-list", f"--max-count={limit}", "HEAD"], cwd=root, timeout=60)
    return {line.strip() for line in out.splitlines() if line.strip()}
