"""Diff reviewer for factory tasks using structured generation."""

from __future__ import annotations

import logging
from typing import Any, Callable

from acp.agent import AcpAgent
from factory.models import Review, Task

logger = logging.getLogger(__name__)

# Upper bound on diff characters forwarded to the agent to prevent token exhaustion.
DIFF_REVIEW_MAX_CHARS = 200_000


def review_diff(
    agent: AcpAgent | None,
    task: Task,
    diff: str,
    base_context: dict[str, Any] | None = None,
    timeout: int = 300,
    cancelled: Callable[[], bool] = lambda: False,
) -> Review:
    """Review a git diff against task acceptance criteria using AcpAgent.

    Args:
        agent: AcpAgent instance used for structured generation (instantiated if None).
        task: The task being reviewed, containing acceptance criteria.
        diff: The git diff generated by the worker.
        base_context: Optional additional context dictionary.
        timeout: Execution timeout in seconds (default 300).
        cancelled: Callable returning True if cancellation was requested.

    Returns:
        Review instance containing decision ('approved' or 'rejected'), findings,
        and confidence score.
    """
    review_agent = agent if agent is not None else AcpAgent()

    bounded_diff = diff
    if len(bounded_diff) > DIFF_REVIEW_MAX_CHARS:
        bounded_diff = (
            bounded_diff[:DIFF_REVIEW_MAX_CHARS]
            + f"\n\n[DIFF TRUNCATED: showing first {DIFF_REVIEW_MAX_CHARS} characters of {len(diff)}]"
        )

    context: dict[str, Any] = {
        "task_id": task.id,
        "title": task.title,
        "instructions": task.instructions,
        "acceptance": task.acceptance,
        "diff": bounded_diff,
    }
    if base_context:
        context.update(base_context)

    instruction = (
        "You are an expert code reviewer evaluating a git diff for a software factory task.\n"
        "Evaluate the git diff against the task acceptance criteria.\n"
        "Evaluation guidelines:\n"
        "1. Assess whether the diff satisfies all task acceptance criteria.\n"
        "2. Ensure there are no out-of-scope files, unnecessary deletions, or secrets.\n"
        "3. Check for logic bugs, broken tests, or missing edge case handling.\n"
        "4. Return decision='approved' if the diff meets all requirements with high confidence.\n"
        "5. Return decision='rejected' if any acceptance criteria are missing or issues are identified, "
        "and provide specific, actionable items in the 'findings' list.\n"
        "6. Set confidence score between 0.0 and 1.0."
    )

    return review_agent.generate(
        role="Diff Reviewer",
        instruction=instruction,
        context=context,
        schema=Review,
        timeout=timeout,
        cancelled=cancelled,
    )
